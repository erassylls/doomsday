function nonempty(value: unknown, maximum: number): boolean {
  return typeof value === 'string' && value.trim().length > 0 && value.length <= maximum;
}

/** Runtime validation also protects imports/API requests, not only the TypeScript UI. */
export function validateChecklist(criteria: unknown): string[] {
  if (!Array.isArray(criteria) || criteria.length === 0) return ['Добавьте хотя бы один критерий.'];
  if (criteria.length > 100) return ['Допускается не более 100 критериев.'];
  const errors: string[] = [];
  const ids = new Set<string>();
  criteria.forEach((raw, index) => {
    const prefix = `Критерий ${index + 1}`;
    if (!raw || typeof raw !== 'object' || Array.isArray(raw)) {
      errors.push(`${prefix}: неверный формат.`);
      return;
    }
    const item = raw as Criterion;
    if (!nonempty(item.id, 100) || !/^[a-zA-Z0-9_-]+$/.test(item.id)) {
      errors.push(`${prefix}: ID должен состоять из букв, цифр, «_» или «-».`);
    } else if (ids.has(item.id)) errors.push(`${prefix}: ID «${item.id}» повторяется.`);
    else ids.add(item.id);
    if (!nonempty(item.name, 300)) errors.push(`${prefix}: укажите название до 300 символов.`);
    if (!nonempty(item.section, 300)) errors.push(`${prefix}: укажите раздел до 300 символов.`);
    if (!nonempty(item.description, 12000)) errors.push(`${prefix}: укажите правило оценки до 12 000 символов.`);
    if (!['boolean', 'scale', 'flag'].includes(item.kind)) errors.push(`${prefix}: неизвестный тип оценки.`);
    if (typeof item.weight !== 'number' || !Number.isFinite(item.weight) || item.weight < 0 || item.weight > 1000000) {
      errors.push(`${prefix}: вес должен быть числом от 0 до 1 000 000.`);
    }
    if (item.kind === 'flag' && item.weight !== 0) errors.push(`${prefix}: у флага грубой ошибки вес должен быть 0.`);
    if (typeof item.allowNA !== 'boolean') errors.push(`${prefix}: укажите, разрешён ли N/A.`);
    if (typeof item.naCondition !== 'string' || item.naCondition.length > 12000) errors.push(`${prefix}: неверное условие N/A.`);
    if (item.allowNA && !nonempty(item.naCondition, 12000)) errors.push(`${prefix}: для N/A требуется явное условие неприменимости.`);
    if (!Array.isArray(item.levels)) {
      errors.push(`${prefix}: шкала должна быть массивом.`);
    } else if (item.kind === 'scale') {
      if (item.levels.length < 2 || item.levels.length > 50) errors.push(`${prefix}: шкала должна содержать от 2 до 50 ступеней.`);
      const values = new Set<number>();
      item.levels.forEach((level) => {
        if (!level || typeof level !== 'object' || typeof level.value !== 'number' || !Number.isFinite(level.value) || level.value < 0 || level.value > 1000000000) {
          errors.push(`${prefix}: ступени шкалы должны быть конечными неотрицательными числами.`);
          return;
        }
        if (values.has(level.value)) errors.push(`${prefix}: значение ${level.value} в шкале повторяется.`);
        values.add(level.value);
        if (!nonempty(level.label, 4000)) errors.push(`${prefix}: каждой ступени нужно описание до 4 000 символов.`);
      });
      if (![...values].some((value) => value > 0)) errors.push(`${prefix}: максимальная ступень должна быть больше нуля.`);
    } else if (item.levels.length > 0) errors.push(`${prefix}: ступени нужны только шкальному критерию.`);
  });
  return [...new Set(errors)];
}
